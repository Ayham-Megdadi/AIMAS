def compute_entropy(image_path: str) -> float:
    try:
        img = Image.open(image_path).convert('L')
        pixels = np.array(img).flatten()
        hist = np.histogram(pixels, bins=256, range=(0, 256))[0]
        hist = hist / hist.sum()
        entropy = -np.sum(hist * np.log2(hist + 1e-10))
        return entropy
    except:
        return 0.0


def detect_ai(image_path: str, metadata: dict) -> tuple:
    reasons = []
    confidence = 0.0
    ai_keywords = {
        "Software": ["midjourney", "dall-e", "stable diffusion", "adobe firefly", "leonardo ai",
                     "playground ai", "nightcafe", "deepai", "craiyon", "wombo", "dream"],
        "Description": ["ai generated", "artificial intelligence", "prompt", "generated by"],
        "Copyright": ["ai", "generated"],
        "Creator": ["ai", "generated"],
        "Artist": ["ai", "generated"],
        "Make": ["ai"],
        "Model": ["dall-e", "midjourney", "stable diffusion"],
        "XMP:CreatorTool": ["midjourney", "dall-e", "stable diffusion"],
        "XMP:Generator": ["ai"],
        "XMP:Manifest": ["ai"],
        "Exif:ImageDescription": ["ai generated"]
    }
    for field, patterns in ai_keywords.items():
        if field in metadata:
            val = str(metadata[field]).lower()
            for pat in patterns:
                if pat in val:
                    reasons.append(f"{field}: '{pat}'")
                    confidence += 0.25
                    break
    has_camera_make = any(f in metadata for f in ["Make", "Model", "GPSInfo", "GPSLatitude"])
    if not has_camera_make:
        reasons.append("Missing typical camera EXIF (Make/Model/GPS)")
        confidence += 0.2
    entropy = compute_entropy(image_path)
    if entropy > 7.5:
        reasons.append(f"High image entropy ({entropy:.2f}) - typical of AI generation")
        confidence += 0.25
    elif entropy < 5.0:
        reasons.append(f"Low image entropy ({entropy:.2f}) - possibly simple graphics")
        confidence -= 0.1
    confidence = max(0.0, min(1.0, confidence))
    is_ai = confidence >= 0.4
    return is_ai, confidence, reasons


# ----------------------------------------------------------------------
# Worker with rich metadata extraction (exiftool preferred, then PIL+)
# ----------------------------------------------------------------------
class MetadataExtractWorker(QThread):
    metadata_ready = pyqtSignal(dict)
    ai_detection_result = pyqtSignal(bool, float, list)
    sensitive_found = pyqtSignal(str, str)
    finished = pyqtSignal()
    error = pyqtSignal(str)

    def __init__(self, filepath: str):
        super().__init__()
        self.filepath = filepath
        self._abort = False

    def abort(self):
        self._abort = True

    def run(self):
        try:
            metadata = {}
            # Prefer exiftool for maximum details
            exiftool = shutil.which('exiftool')
            if exiftool:
                try:
                    proc = subprocess.run(
                        [exiftool, '-j', '-n', self.filepath],
                        capture_output=True, text=True, timeout=30
                    )
                    if proc.returncode == 0 and proc.stdout.strip():
                        metadata = json.loads(proc.stdout)[0]
                    else:
                        logger.warning("exiftool returned no data, falling back to PIL")
                except Exception as e:
                    logger.warning(f"exiftool error: {e}, falling back to PIL")
            # If exiftool failed or not installed, use PIL + file info
            if not metadata:
                img = Image.open(self.filepath)
                exif = img._getexif()
                if exif:
                    for tag_id, value in exif.items():
                        tag_name = ExifTags.TAGS.get(tag_id, tag_id)
                        metadata[tag_name] = str(value)
                # Add essential file info
                stat = Path(self.filepath).stat()
                metadata["FileType"] = img.format or "Unknown"
                metadata["ImageSize"] = f"{img.width}x{img.height}"
                metadata["FileSize"] = f"{stat.st_size} bytes"
                metadata["LastModified"] = datetime.fromtimestamp(stat.st_mtime).strftime("%Y-%m-%d %H:%M:%S")
            # Emit rich metadata
            self.metadata_ready.emit(metadata)
            if self._abort:
                return

            # AI detection
            is_ai, conf, reasons = detect_ai(self.filepath, metadata)
            self.ai_detection_result.emit(is_ai, conf, reasons)
            if self._abort:
                return

            # Sensitive data detection (using common sensitive fields)
            sensitive_fields = [
                'Artist', 'Author', 'OwnerName', 'Creator', 'Copyright',
                'GPSLatitude', 'GPSLongitude', 'GPSAltitude', 'GPSInfo',
                'SerialNumber', 'CreateDate', 'ModifyDate', 'DateTimeOriginal',
                'XPComment', 'XPAuthor', 'XPKeywords', 'XPSubject'
            ]
            for field in sensitive_fields:
                if field in metadata and metadata[field]:
                    self.sensitive_found.emit(field, str(metadata[field])[:200])
            self.finished.emit()
        except Exception as e:
            self.error.emit(str(e))


